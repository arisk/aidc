import type { AiComponent, AiEntry, ReqRule } from '../../src/ai/dictionary.ts';
import type { Cset } from '../../src/core/cset.ts';
import { isLinterName, type LinterName } from '../../src/ai/linters/index.ts';

const COMPONENT_RE = /^(\[)?([NXYZ])(?:(\d+)|\.\.(\d+))(\])?((?:,[a-z0-9]+)*)$/;

function toCset(c: string | undefined, line: number): Cset {
  if (c === 'N' || c === 'X' || c === 'Y' || c === 'Z') return c;
  throw new Error(`line ${line}: bad character set "${c}"`);
}

function parseComponent(token: string, line: number): AiComponent {
  const m = COMPONENT_RE.exec(token);
  if (!m) throw new Error(`line ${line}: bad component "${token}"`);
  const [, open, cset, fixed, varMax, close, lints = ''] = m;
  if (Boolean(open) !== Boolean(close))
    throw new Error(`line ${line}: unbalanced brackets in "${token}"`);
  const linters: LinterName[] = [];
  for (const l of lints.split(',').filter(Boolean)) {
    if (!isLinterName(l)) throw new Error(`line ${line}: unknown linter "${l}"`);
    linters.push(l);
  }
  const min = fixed ? Number(fixed) : 1;
  const max = fixed ? Number(fixed) : Number(varMax);
  return {
    cset: toCset(cset, line),
    min,
    max,
    optional: Boolean(open),
    linters,
  };
}

function expandAis(token: string, line: number): string[] {
  const [from = '', to] = token.split('-');
  if (!/^\d{2,4}$/.test(from)) throw new Error(`line ${line}: bad AI "${token}"`);
  if (to === undefined) return [from];
  if (to.length !== from.length) throw new Error(`line ${line}: bad AI range "${token}"`);
  const out: string[] = [];
  for (let n = Number(from); n <= Number(to); n++) out.push(String(n).padStart(from.length, '0'));
  return out;
}

export function parseSyntaxDictionary(text: string): { release: string; entries: AiEntry[] } {
  const release = /^#\s*Release:\s*(\S+)/m.exec(text)?.[1];
  if (!release) throw new Error('missing "# Release:" header');
  const entries: AiEntry[] = [];
  text.split('\n').forEach((raw, idx) => {
    const line = idx + 1;
    if (/^\s*(#|$)/.test(raw)) return;
    const hash = raw.indexOf('#');
    const title = hash === -1 ? '' : raw.slice(hash + 1).trim();
    const tokens = (hash === -1 ? raw : raw.slice(0, hash)).trim().split(/\s+/);
    const aiToken = tokens.shift() ?? '';
    let flags = '';
    if (tokens[0] !== undefined && !COMPONENT_RE.test(tokens[0])) flags = tokens.shift() ?? '';
    const components: AiComponent[] = [];
    while (tokens[0] !== undefined && COMPONENT_RE.test(tokens[0]))
      components.push(parseComponent(tokens.shift() ?? '', line));
    if (components.length === 0) throw new Error(`line ${line}: no components`);
    const req: ReqRule[] = [];
    const ex: string[] = [];
    let dlpkey: string[][] | undefined;
    for (const attr of tokens) {
      const eq = attr.indexOf('=');
      const key = eq === -1 ? attr : attr.slice(0, eq);
      const value = eq === -1 ? undefined : attr.slice(eq + 1);
      if (key === 'req' && value) req.push(value.split(',').map((g) => g.split('+')));
      else if (key === 'ex' && value) ex.push(...value.split(','));
      else if (key === 'dlpkey') dlpkey = value ? value.split('|').map((s) => s.split(',')) : [[]];
      else throw new Error(`line ${line}: unknown attribute "${attr}"`);
    }
    for (const ai of expandAis(aiToken, line)) {
      const entry: AiEntry = {
        ai,
        title,
        fnc1: !flags.includes('*'),
        dlAttr: flags.includes('?'),
        components,
        req,
        ex,
        ...(dlpkey ? { dlpkey } : {}),
      };
      entries.push(entry);
    }
  });
  return { release, entries };
}

export function renderAiTable(
  release: string,
  entries: readonly AiEntry[],
  sourcePath: string,
): string {
  const rows = entries.map((e) => `  ${JSON.stringify(e)},`).join('\n');
  return [
    `// Generated by scripts/gen-ai-table.ts from ${sourcePath}. Do not edit; run \`pnpm gen\`.`,
    '// Source data: GS1 Barcode Syntax Dictionary, Apache-2.0, Copyright (c) 2021-2025 GS1 AISBL (and BWIPP, Zint). See THIRD_PARTY_NOTICES.md.',
    "import type { AiEntry } from './dictionary.ts';",
    '',
    `export const SYNTAX_DICTIONARY_RELEASE: string = ${JSON.stringify(release)};`,
    '',
    'export const AI_TABLE: readonly AiEntry[] = [',
    rows,
    '];',
    '',
  ].join('\n');
}
