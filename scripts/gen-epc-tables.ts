import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const TDT_DIR = 'docs/specifications/data/tdt-2.3-draft-2026-09-15a';
export const TDT_RELEASE = '2.3 draft 2026-09-15a';
const OUTPUT = 'src/epc/tables.gen.ts';

/** TDT Table F method text -> TableFMethod. Unknown text throws. */
export const METHOD_BY_TEXT: ReadonlyMap<string, string> = new Map([
  ['Fixed-length numeric', 'FLN'],
  ['Fixed-Bit-Length Numeric String', 'FBL'],
  ['Variable-length alphanumeric', 'ALN'],
  ['Delimited/terminated numeric', 'DTN'],
  ['Variable-length numeric string without encoding indicator', 'VN'],
  ['6-digit date YYMMDD', 'DATE6'],
  ['10-digit date+time YYMMDDhhmm', 'DATE10'],
  ['Variable-format date / date range', 'DATERANGE'],
  ['Variable-precision date+time', 'DATETIME'],
  ['Country code (ISO 3166-1 alpha-2)', 'COUNTRY'],
  ['Single data bit', 'BIT'],
  ['Optional minus sign in 1 bit', 'MINUS'],
  ['Sequence indicator', 'SEQ'],
]);

type Row = Readonly<Record<string, string | undefined>>;
interface Table {
  readonly rows: readonly Row[];
}

function readTable(name: string): Table {
  const text = readFileSync(`${TDT_DIR}/TDT_Table${name}.json`, 'utf8');
  // oxlint-disable-next-line typescript/no-unsafe-type-assertion -- trusted TDT JSON
  return JSON.parse(text) as Table;
}

function num(row: Row, col: string | undefined): number {
  const v = col === undefined ? undefined : row[col];
  if (v === undefined) return 0;
  if (!/^\d+$/.test(v)) throw new Error(`Table F ${row['a']}: column ${col} is not numeric: ${v}`);
  return Number(v);
}

function component(row: Row, cols: readonly string[]): string | undefined {
  const [format, , d, e, f, g, h] = cols;
  const text = row[format ?? ''];
  if (text === undefined) return undefined;
  const method = METHOD_BY_TEXT.get(text);
  if (method === undefined) throw new Error(`Table F ${row['a']}: unknown method "${text}"`);
  return (
    `{ method: '${method}', fixedChars: ${num(row, d)}, fixedBits: ${num(row, e)}, ` +
    `indicatorBits: ${num(row, f)}, lengthBits: ${num(row, g)}, maxChars: ${num(row, h)} }`
  );
}

/** Table F distinct method texts, for the drift/mapping test. */
export function tableFMethodTexts(): string[] {
  const texts = new Set<string>();
  for (const row of readTable('F').rows) {
    for (const col of ['b', 'i']) {
      const t = row[col];
      if (t !== undefined) texts.add(t);
    }
  }
  return [...texts];
}

export function renderEpcTables(): string {
  const f = readTable('F').rows.map((row) => {
    const ai = row['a'];
    if (ai === undefined) throw new Error('Table F row without AI');
    const comps = [
      component(row, ['b', 'c', 'd', 'e', 'f', 'g', 'h']),
      component(row, ['i', 'j', 'k', 'l', 'm', 'n', 'o']),
    ].filter((c): c is string => c !== undefined);
    if (comps.length === 0) throw new Error(`Table F ${ai}: no component`);
    return `  ['${ai}', [${comps.join(', ')}]],`;
  });
  const a = readTable('A')
    .rows.filter((r) => r['c'] !== undefined)
    .map((r) => `  [${JSON.stringify(r['a'])}, ${JSON.stringify(r['c'])}],`);
  const b = ['B1', 'B2', 'B3', 'B4'].flatMap((n) =>
    readTable(n)
      .rows.filter((r) => !/^Reserved/i.test(r['b'] ?? ''))
      .map((r) => `  [${JSON.stringify(r['a'])}, ${JSON.stringify(r['b'])}],`),
  );
  return [
    `// Generated by scripts/gen-epc-tables.ts from ${TDT_DIR}/TDT_Table{A,B1,B2,B3,B4,F}.json. Do not edit; run \`pnpm gen\`.`,
    `// Source data: GS1 Tag Data Translation (TDT) ${TDT_RELEASE}, gs1/TDT, Apache-2.0, Copyright GS1 AISBL.`,
    '',
    'export type TableFMethod =',
    "  | 'FLN'",
    "  | 'FBL'",
    "  | 'ALN'",
    "  | 'DTN'",
    "  | 'VN'",
    "  | 'DATE6'",
    "  | 'DATE10'",
    "  | 'DATERANGE'",
    "  | 'DATETIME'",
    "  | 'COUNTRY'",
    "  | 'BIT'",
    "  | 'MINUS'",
    "  | 'SEQ';",
    '',
    'export interface TableFComponent {',
    '  readonly method: TableFMethod;',
    '  /** Fixed character count as in TDT Table F, else 0. */',
    '  readonly fixedChars: number;',
    '  /** Fixed bit count as in TDT Table F, else 0. */',
    '  readonly fixedBits: number;',
    '  /** Encoding indicator bits (3 or more for ALN, DTN), else 0. */',
    '  readonly indicatorBits: number;',
    '  /** Length indicator bits (ALN, DTN remainder, VN), else 0. */',
    '  readonly lengthBits: number;',
    '  /** Maximum characters as in TDT Table F, else 0. */',
    '  readonly maxChars: number;',
    '}',
    '',
    `export const TDT_TABLES_RELEASE: string = ${JSON.stringify(TDT_RELEASE)};`,
    '',
    '/** AI to its one or two Table F components. */',
    'export const TABLE_F: ReadonlyMap<string, readonly TableFComponent[]> = /* @__PURE__ */ new Map<',
    '  string,',
    '  readonly TableFComponent[]',
    '>([',
    ...f,
    ']);',
    '',
    '/** Optimisation Table A: 7-bit code to special subdomain or TLD. */',
    'export const HOSTNAME_TABLE_A: ReadonlyMap<string, string> = /* @__PURE__ */ new Map<string, string>([',
    ...a,
    ']);',
    '',
    '/** Optimisation Tables B1 to B4: 14-bit code to TLD. Reserved codes are omitted. */',
    'export const HOSTNAME_TABLE_B: ReadonlyMap<string, string> = /* @__PURE__ */ new Map<string, string>([',
    ...b,
    ']);',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = renderEpcTables();
  writeFileSync(OUTPUT, out);
  console.log(`wrote ${OUTPUT}`);
}
